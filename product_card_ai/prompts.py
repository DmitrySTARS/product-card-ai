"""Промпты.

Главное требование задания — модель не должна выдумывать характеристики.
Поэтому промпт построен так:

1. Системная часть задаёт роль, жёсткие запреты и формат ответа (строгий JSON).
2. Пользовательская часть отдаёт данные тоже в виде JSON и явно перечисляет,
   каких полей не хватает, чтобы модель не пыталась «починить» пробел догадкой.
3. Все числовые значения разрешено брать только из блока входных данных —
   это дублируется и в системном, и в пользовательском сообщении, потому что
   на длинном контексте одно упоминание модели часто игнорируют.
"""

from __future__ import annotations

import json

from .models import NO_DATA, InputReport, ProductInput

TITLE_MAX = 70
DESCRIPTION_MIN = 800
DESCRIPTION_MAX = 1200
QUERIES_MIN = 3
QUERIES_MAX = 5

SYSTEM_PROMPT = f"""\
Ты — контент-редактор B2B-интернет-магазина контрольно-измерительных приборов.
Ты готовишь черновик карточки товара, который затем проверит контент-менеджер.

ЖЁСТКИЕ ПРАВИЛА (нарушение любого из них делает ответ непригодным):
1. Используй ТОЛЬКО те факты, которые есть во входных данных. Запрещено
   добавлять, уточнять, округлять или «восстанавливать по смыслу» любые
   технические значения: диапазоны, классы точности, напряжения, резьбы,
   габариты, материалы, протоколы, сертификаты, гарантию, цену, сроки поставки.
2. Если характеристики нет во входных данных — пиши ровно «{NO_DATA}».
   Не пропускай такое поле молча и не заменяй его общими словами.
3. Не придумывай названия стандартов (ГОСТ, ТУ, IP, ATEX и т. п.), если они не
   указаны во входных данных.
4. В тексте не должно быть чисел, которых нет во входных данных. Единственное
   исключение — числа, которые уже содержатся в названии товара.
5. Пиши по-русски, в деловом стиле, без превосходных степеней и рекламных
   обещаний («лучший», «непревзойдённый», «гарантируем»).

ФОРМАТ ОТВЕТА: верни ТОЛЬКО валидный JSON, без обёртки в кодовый блок и без
комментариев, строго по схеме:
{{
  "seo_title": "строка, не длиннее {TITLE_MAX} символов",
  "seo_description": "строка длиной от {DESCRIPTION_MIN} до {DESCRIPTION_MAX} символов",
  "key_specs": [{{"label": "название характеристики", "value": "значение или {NO_DATA}"}}],
  "search_queries": ["от {QUERIES_MIN} до {QUERIES_MAX} поисковых запросов"],
  "commercial_block": {{
    "audience": "кому подходит прибор",
    "tasks": "какие задачи решает"
  }},
  "missing_data": ["каких данных не хватает для полноценной карточки"]
}}

Требования к содержанию полей:
- seo_title: включает тип прибора, модель и производителя, если они известны.
- seo_description: связный текст для страницы товара, опирается на описание и
  характеристики из входных данных. Нельзя дописывать факты «для объёма» —
  лучше раскрыть применение и назначение, чем выдумать параметр.
- key_specs: все характеристики из входных данных плюс отсутствующие типовые
  характеристики со значением «{NO_DATA}».
- search_queries: реальные коммерческие запросы, под которые логично
  оптимизировать страницу (тип прибора + модель, производитель, купить, цена,
  ключевой параметр). Запрос не должен содержать выдуманных параметров.
- commercial_block: короткая подсказка менеджеру, без технических догадок.
- missing_data: перечисли пробелы входных данных человеческим языком.
"""


def build_user_prompt(product: ProductInput, report: InputReport) -> str:
    """Собрать пользовательское сообщение для модели."""
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or None,
        "specs": product.specs or {},
        "description": product.description or None,
    }
    data_block = json.dumps(payload, ensure_ascii=False, indent=2)

    lines = [
        "Входные данные о товаре (единственный разрешённый источник фактов).",
        "JSON находится между строками НАЧАЛО ДАННЫХ и КОНЕЦ ДАННЫХ:",
        "НАЧАЛО ДАННЫХ",
        data_block,
        "КОНЕЦ ДАННЫХ",
    ]

    if report.missing_fields:
        lines.append("")
        lines.append("Этих полей во входных данных НЕТ. Не восстанавливай их по смыслу,")
        lines.append(f"ставь «{NO_DATA}» и перечисли их в missing_data:")
        lines.extend(f"- {item}" for item in report.missing_fields)

    if report.needs_clarification:
        lines.append("")
        lines.append("Замечания по качеству входных данных:")
        lines.extend(f"- {item}" for item in report.needs_clarification)

    lines.append("")
    lines.append(
        "Сформируй черновик карточки строго по схеме из системного сообщения. "
        "Повторяю: любое числовое значение в ответе должно встречаться во входных "
        f"данных выше; если данных нет — пиши «{NO_DATA}»."
    )
    return "\n".join(lines)
